-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ----------------------------------------------------------------------------
-- 1. PROFILES TABLE (User/Student details)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    college TEXT DEFAULT '',
    avatar_url TEXT DEFAULT '',
    total_xp INTEGER DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 2. ROOMS TABLE (Quiz sessions & hosted arenas)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.rooms (
    room_code TEXT PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Quant', -- 'Quant', 'Logic', 'Verbal', 'Data Interpretation'
    host_name TEXT NOT NULL DEFAULT 'Host',
    status TEXT NOT NULL DEFAULT 'lobby', -- 'lobby', 'live', 'starting-soon', 'completed'
    current_round INTEGER DEFAULT 1,
    total_rounds INTEGER DEFAULT 15,
    is_locked BOOLEAN DEFAULT FALSE,
    timer_frozen BOOLEAN DEFAULT FALSE,
    broadcast_message TEXT DEFAULT '',
    max_players INTEGER DEFAULT 50,
    tags TEXT[] DEFAULT ARRAY[]::TEXT[],
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 3. QUESTIONS TABLE (Question bank & room-specific questions)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code TEXT REFERENCES public.rooms(room_code) ON DELETE CASCADE,
    category TEXT NOT NULL DEFAULT 'Quant',
    section TEXT NOT NULL DEFAULT 'Section A',
    topic TEXT NOT NULL,
    question TEXT NOT NULL,
    options JSONB NOT NULL, -- Array of { "key": "A", "text": "...", "percentage": 0, "count": 0, "isCorrect": true }
    correct_key TEXT NOT NULL, -- 'A', 'B', 'C', or 'D'
    official_answer_text TEXT NOT NULL,
    standard_pace_sec INTEGER DEFAULT 45,
    max_points INTEGER DEFAULT 1000,
    scratchpad_formula TEXT DEFAULT '',
    explanation TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 4. ROOM_PLAYERS TABLE (Players actively in a quiz session)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.room_players (
    id TEXT PRIMARY KEY, -- Unique player session ID (or UUID)
    room_code TEXT NOT NULL REFERENCES public.rooms(room_code) ON DELETE CASCADE,
    user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    college TEXT DEFAULT '',
    initials TEXT DEFAULT '',
    score INTEGER DEFAULT 0,
    rank INTEGER DEFAULT 1,
    streak_count INTEGER DEFAULT 0,
    accuracy_rate NUMERIC(5, 2) DEFAULT 0.00,
    status TEXT DEFAULT 'active', -- 'top-seed', 'ready', 'streak', 'active'
    is_current_user BOOLEAN DEFAULT FALSE,
    joined_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 5. PERFORMANCE_HISTORY TABLE (Per-round player results & speed telemetry)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.performance_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code TEXT NOT NULL REFERENCES public.rooms(room_code) ON DELETE CASCADE,
    player_id TEXT NOT NULL REFERENCES public.room_players(id) ON DELETE CASCADE,
    round INTEGER NOT NULL,
    round_name TEXT DEFAULT '',
    topic TEXT DEFAULT '',
    selected_key TEXT,
    is_correct BOOLEAN DEFAULT FALSE,
    score_earned INTEGER DEFAULT 0,
    cumulative_xp INTEGER DEFAULT 0,
    latency_sec NUMERIC(5, 2) DEFAULT 0.00,
    rank INTEGER DEFAULT 1,
    accuracy NUMERIC(5, 2) DEFAULT 0.00,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc', NOW()) NOT NULL
);

-- ----------------------------------------------------------------------------
-- 6. ACHIEVEMENTS TABLE (Achievement badge templates)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.achievements (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL, -- 'points', 'speed', 'streak', 'accuracy'
    description TEXT NOT NULL,
    icon_name TEXT NOT NULL,
    milestone_points INTEGER NOT NULL,
    tier TEXT NOT NULL, -- 'bronze', 'silver', 'gold', 'diamond'
    badge_label TEXT NOT NULL
);

-- ----------------------------------------------------------------------------
-- INDEXES FOR PERFORMANCE
-- ----------------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_questions_room_code ON public.questions(room_code);
CREATE INDEX IF NOT EXISTS idx_questions_category ON public.questions(category);
CREATE INDEX IF NOT EXISTS idx_room_players_room_code ON public.room_players(room_code);
CREATE INDEX IF NOT EXISTS idx_room_players_score ON public.room_players(score DESC);
CREATE INDEX IF NOT EXISTS idx_performance_history_player ON public.performance_history(player_id);
CREATE INDEX IF NOT EXISTS idx_performance_history_room ON public.performance_history(room_code);

-- ----------------------------------------------------------------------------
-- ROW LEVEL SECURITY (RLS)
-- ----------------------------------------------------------------------------
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.room_players ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.performance_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.achievements ENABLE ROW LEVEL SECURITY;

-- Allow public read/write access for game arena interactions (Anon key access)
CREATE POLICY "Public read profiles" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Public insert profiles" ON public.profiles FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update profiles" ON public.profiles FOR UPDATE USING (true);

CREATE POLICY "Public read rooms" ON public.rooms FOR SELECT USING (true);
CREATE POLICY "Public insert rooms" ON public.rooms FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update rooms" ON public.rooms FOR UPDATE USING (true);
CREATE POLICY "Public delete rooms" ON public.rooms FOR DELETE USING (true);

CREATE POLICY "Public read questions" ON public.questions FOR SELECT USING (true);
CREATE POLICY "Public insert questions" ON public.questions FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update questions" ON public.questions FOR UPDATE USING (true);
CREATE POLICY "Public delete questions" ON public.questions FOR DELETE USING (true);

CREATE POLICY "Public read room_players" ON public.room_players FOR SELECT USING (true);
CREATE POLICY "Public insert room_players" ON public.room_players FOR INSERT WITH CHECK (true);
CREATE POLICY "Public update room_players" ON public.room_players FOR UPDATE USING (true);
CREATE POLICY "Public delete room_players" ON public.room_players FOR DELETE USING (true);

CREATE POLICY "Public read performance_history" ON public.performance_history FOR SELECT USING (true);
CREATE POLICY "Public insert performance_history" ON public.performance_history FOR INSERT WITH CHECK (true);

CREATE POLICY "Public read achievements" ON public.achievements FOR SELECT USING (true);

